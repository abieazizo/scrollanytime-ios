#!/usr/bin/env bash
# Build the iOS shell on GitHub's FREE public-repository macOS runners.
#
# WHY THIS EXISTS. The app is a thin WKWebView shell around scrollanytime.com; every native change
# (the status-bar band, the launch screen) needs a Mac to compile, and the only Mac this project has
# is a GitHub Actions runner. Private repositories bill macOS minutes at ten times the rate and the
# account's allowance ran out; public repositories get standard runners for free. So this mirrors
# ONLY the shell and its build workflow into a public repository under the owner's account.
#
# WHAT IS MIRRORED: ship/ios (Swift, storyboards, plist, icons, the offline page), the three
# fastlane files, the lint and its two helpers, and the release workflow with the listing,
# screenshot and submission steps REMOVED. WHAT IS NOT: the web app, the worker, ingestion,
# ship/metadata (the review notes carry the review account's code), the screenshots, any secret.
# The three App Store Connect secrets are set on the mirror as encrypted repository secrets.
#
# The mirror only BUILDS and UPLOADS. Submitting the build to App Review is done afterwards
# through the App Store Connect API, exactly as before.
#
#   GITHUB_TOKEN=ghp_…  ASC_P8=/path/to/AuthKey_XXXX.p8  bash ship/mirror-ios-public.sh [build_number]
#
# Runs only with the owner's explicit go-ahead: it publishes source code.
set -euo pipefail

: "${GITHUB_TOKEN:?set GITHUB_TOKEN (needs repo + workflow scopes)}"
: "${ASC_P8:?set ASC_P8 to the App Store Connect .p8 key file}"
ASC_KEY_ID="${ASC_KEY_ID:-XP57NY3CT3}"
ASC_ISSUER_ID="${ASC_ISSUER_ID:-f864970e-7eb9-420b-a192-1abb1428f805}"
OWNER="${MIRROR_OWNER:-abieazizo}"
REPO="${MIRROR_REPO:-scrollanytime-ios}"
BUILD_NUMBER="${1:-}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SHA="$(git -C "$ROOT" rev-parse --short=12 HEAD)"
PY="${PYTHON:-python}"
API="https://api.github.com"
auth=(-H "Authorization: token $GITHUB_TOKEN" -H "Accept: application/vnd.github+json")

echo "── mirror $SHA → $OWNER/$REPO (public) ──"

# ── 1. the subset ─────────────────────────────────────────────────────────────────────────────
TMP="$(mktemp -d)"
mkdir -p "$TMP/ship/fastlane" "$TMP/.github/workflows"
cp -R "$ROOT/ship/ios" "$TMP/ship/ios"
cp "$ROOT"/ship/fastlane/Appfile "$ROOT"/ship/fastlane/Deliverfile "$ROOT"/ship/fastlane/Fastfile "$TMP/ship/fastlane/"
cp "$ROOT"/ship/ios-lint.sh "$ROOT"/ship/gen-offline-swift.mjs "$ROOT"/ship/gen-ios-assets.mjs "$TMP/ship/"
# the simulator recording (App Review item 1 + the launch's own proof) needs its driver too
mkdir -p "$TMP/ship/demo"
cp -R "$ROOT"/ship/demo/. "$TMP/ship/demo/"
cp "$ROOT/.github/workflows/demo-video.yml" "$TMP/.github/workflows/demo-video.yml"
# the workflow without the steps that need what stays private
"$PY" - "$ROOT/.github/workflows/release-ios.yml" "$TMP/.github/workflows/release-ios.yml" <<'PYEOF'
import sys
src, dst = sys.argv[1], sys.argv[2]
DROP = ('Push both screenshot sets', 'Push listing metadata', 'Submit for review')
out, skipping = [], False
for line in open(src, encoding='utf-8').read().split('\n'):
    if line.startswith('      - name:'):
        skipping = any(line.strip() == f'- name: {n}' for n in DROP)
    if not skipping:
        out.append(line)
text = '\n'.join(out)
text = text.replace("name: release-ios", "name: release-ios\n# MIRROR: generated by ship/mirror-ios-public.sh from the private repository — do not edit here.", 1)
open(dst, 'w', encoding='utf-8', newline='\n').write(text)
print('  workflow mirrored without the listing, screenshot and submit steps')
PYEOF
cat > "$TMP/README.md" <<EOF
# Scroll Anytime — iOS shell (build mirror)

The native shell of [Scroll Anytime](https://scrollanytime.com), mirrored here so GitHub's free
public-repository macOS runners can build it. The product lives at scrollanytime.com; this is the
WKWebView around it. Generated from the private repository at \`$SHA\` by \`ship/mirror-ios-public.sh\`.
EOF
CODE="$(node -e "import('../scripts/_review_code.mjs').then(m=>process.stdout.write(m.reviewCode()))" 2>/dev/null || true)"
grep -rlq "REVIEW_CODE${CODE:+\|$CODE}" "$TMP" && { echo "::error::a review secret would be published — aborting"; exit 1; } || true

# ── 2. the repository ─────────────────────────────────────────────────────────────────────────
if curl -s -o /dev/null -w "%{http_code}" "${auth[@]}" "$API/repos/$OWNER/$REPO" | grep -q 200; then
  echo "  repo exists"
else
  curl -s -o /dev/null -w "  create repo → %{http_code}\n" "${auth[@]}" -X POST "$API/user/repos" \
    -d "{\"name\":\"$REPO\",\"private\":false,\"description\":\"Scroll Anytime — iOS shell build mirror\",\"has_issues\":false,\"has_wiki\":false,\"has_projects\":false}"
  sleep 3
fi

# ── 3. push ───────────────────────────────────────────────────────────────────────────────────
(
  cd "$TMP"
  git init -q -b main
  git add -A
  git -c user.name="Scroll Anytime" -c user.email="hello@scrollanytime.com" commit -q -m "iOS shell mirror from $SHA"
  git push -q -f "https://$GITHUB_TOKEN@github.com/$OWNER/$REPO.git" HEAD:main
)
echo "  pushed $SHA"

# ── 4. secrets (sealed with the repository's public key) ─────────────────────────────────────
"$PY" - "$OWNER" "$REPO" "$ASC_KEY_ID" "$ASC_ISSUER_ID" "$ASC_P8" <<'PYEOF'
import base64, json, os, sys, urllib.request
from nacl import encoding, public
owner, repo, key_id, issuer, p8 = sys.argv[1:6]
tok = os.environ['GITHUB_TOKEN']
def api(method, path, body=None):
    r = urllib.request.Request('https://api.github.com' + path, data=json.dumps(body).encode() if body else None, method=method)
    r.add_header('Authorization', 'token ' + tok); r.add_header('Accept', 'application/vnd.github+json')
    with urllib.request.urlopen(r) as resp:
        raw = resp.read(); return resp.status, (json.loads(raw) if raw else None)
_, pk = api('GET', f'/repos/{owner}/{repo}/actions/secrets/public-key')
sealed = public.SealedBox(public.PublicKey(pk['key'].encode(), encoding.Base64Encoder()))
def put(name, value):
    enc = base64.b64encode(sealed.encrypt(value.encode())).decode()
    st, _ = api('PUT', f'/repos/{owner}/{repo}/actions/secrets/{name}', {'encrypted_value': enc, 'key_id': pk['key_id']})
    print(f'  secret {name} → {st}')
put('ASC_KEY_ID', key_id)
put('ASC_ISSUER_ID', issuer)
put('ASC_KEY_P8_BASE64', base64.b64encode(open(p8, 'rb').read()).decode())
PYEOF

# ── 5. build ──────────────────────────────────────────────────────────────────────────────────
inputs="{\"submit_for_review\":false,\"skip_upload\":false,\"compile_only\":false"
[ -n "$BUILD_NUMBER" ] && inputs="$inputs,\"build_number\":\"$BUILD_NUMBER\""
inputs="$inputs}"
sleep 4
curl -s -o /dev/null -w "  dispatch release-ios → %{http_code}\n" "${auth[@]}" -X POST \
  "$API/repos/$OWNER/$REPO/actions/workflows/release-ios.yml/dispatches" -d "{\"ref\":\"main\",\"inputs\":$inputs}"
echo "  https://github.com/$OWNER/$REPO/actions"
rm -rf "$TMP"
